SET NOCOUNT ON;
SET XACT_ABORT ON;
BEGIN TRAN;
DECLARE @nd INT = (SELECT IDNDERMARJE FROM T_NDERMARJE WHERE NDERMARJEKODI = 'AVEC');
DECLARE @ids TABLE (id INT);
INSERT INTO @ids SELECT IDNRAUTOM FROM T_NRAUTOM
WHERE IDNDERMARJE = @nd AND KODINRAUTOM IN ('FSH','OSH','USH','KSH','Hyrje','Dalje','Banka','Arka','FK')
  AND EMERTIMINRAUTOM LIKE 'Numer automatik per %';

UPDATE T_ATRIBUTETRUPI SET IDNRAUTOMATIK = NULL WHERE IDNRAUTOMATIK IN (SELECT id FROM @ids);
DELETE FROM T_NRAUTOMATIKFUNDITHISTORIK WHERE IDNRAUTOM IN (SELECT id FROM @ids);
DELETE FROM T_NRAUTOMATIKFUNDIT WHERE IDNRAUTOM IN (SELECT id FROM @ids);
DELETE FROM T_NRAUTOM WHERE IDNRAUTOM IN (SELECT id FROM @ids);
COMMIT;

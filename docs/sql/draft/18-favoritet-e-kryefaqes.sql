SET XACT_ABORT ON;
SET NOCOUNT ON;

IF OBJECT_ID('dbo.T_PERDORUES_FAVORITE', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.T_PERDORUES_FAVORITE (
        IDPERDORUES  numeric(18,0) NOT NULL,
        CELESI       nvarchar(300) NOT NULL,
        RENDI        int NOT NULL CONSTRAINT DF_T_PERDORUES_FAVORITE_RENDI DEFAULT (0),
        DTKRIJIMI    datetime NOT NULL CONSTRAINT DF_T_PERDORUES_FAVORITE_DT DEFAULT (GETDATE()),
        CONSTRAINT PK_T_PERDORUES_FAVORITE PRIMARY KEY (IDPERDORUES, CELESI)
    );
END
GO

CREATE OR ALTER PROCEDURE dbo.prc_T_PERDORUES_FAVORITE_sel
    @IDPERDORUES numeric(18,0)
AS
BEGIN
    SET NOCOUNT ON;
    SELECT CELESI FROM dbo.T_PERDORUES_FAVORITE WHERE IDPERDORUES = @IDPERDORUES ORDER BY RENDI, DTKRIJIMI;
END
GO

-- @SHTO = 1 shton yllin, 0 e heq
CREATE OR ALTER PROCEDURE dbo.prc_T_PERDORUES_FAVORITE_ndrysho
    @IDPERDORUES numeric(18,0),
    @CELESI nvarchar(300),
    @SHTO bit
AS
BEGIN
    SET NOCOUNT ON;
    IF @SHTO = 1
    BEGIN
        IF NOT EXISTS (SELECT 1 FROM dbo.T_PERDORUES_FAVORITE WHERE IDPERDORUES = @IDPERDORUES AND CELESI = @CELESI)
            INSERT dbo.T_PERDORUES_FAVORITE (IDPERDORUES, CELESI, RENDI)
            SELECT @IDPERDORUES, @CELESI, ISNULL(MAX(RENDI), 0) + 1 FROM dbo.T_PERDORUES_FAVORITE WHERE IDPERDORUES = @IDPERDORUES;
    END
    ELSE
        DELETE FROM dbo.T_PERDORUES_FAVORITE WHERE IDPERDORUES = @IDPERDORUES AND CELESI = @CELESI;
END
GO

/* Undo 01-lista-me-pak-kolona.sql: puts back the visibility saved in AVEC_BAK_01_GRIDATRUPI, then drops it. */
SET NOCOUNT ON;
SET XACT_ABORT ON;
IF OBJECT_ID('dbo.AVEC_BAK_01_GRIDATRUPI') IS NULL BEGIN PRINT 'Nothing to undo.'; RETURN; END
BEGIN TRAN;
UPDATE t SET t.GRIDATRUPIVISIBLE = b.GRIDATRUPIVISIBLE
FROM T_GRIDATRUPI t JOIN dbo.AVEC_BAK_01_GRIDATRUPI b ON b.GRIDATRUPIID = t.GRIDATRUPIID;
SELECT @@ROWCOUNT AS kolona_te_rikthyera;
DROP TABLE dbo.AVEC_BAK_01_GRIDATRUPI;
COMMIT;

-- 05 - Eksporti i dokumenteve te magazines (Eksport.aspx, kategoria 6)
--
-- prc_T_KOKAMAGAZINA_merrDokMagazineSipasNdermarrjePerEksport per nje vit te klientit (1,5 milion rreshta magazine):
--   - llogariste te 56 kolonat, kurse Eksport.aspx shfaq vetem ato te formatit (~12);
--   - bashkonte cdo rresht me te gjithe tabelen e rreshtave te magazines (DESTINACION) dhe pastaj
--     GROUP BY mbi te 56 kolonat vetem per te hequr dublikatat qe mund te krijonte ai bashkim.
--   ~2 minuta vetem ne SQL.
--
-- Tani (per LLOJI = 1, eksporti ne skedar):
--   - DESTINACION dhe serialet merren te pa-dublikuara (DISTINCT) para bashkimit: dublikatat qe hiqte GROUP BY
--     vinin vetem nga keto dy bashkime (te gjitha te tjerat jane 1:1), keshtu qe rezultati eshte i njejte pa GROUP BY;
--   - parametri opsional @KOLONAT ('Kolona 1|Kolona 2|...'): llogariten vetem kolonat e kerkuara.
-- 1,5 milion rreshta: ~13 sekonda me kolonat e formatit. Pa @KOLONAT kthehen te gjitha kolonat si me pare.
-- LLOJI = 2 (eksporti ne tabela SQL) mbetet si me pare, vetem me DESTINACION te pa-dublikuar (GROUP BY e tij jep te njejtin rezultat).
-- AVEC e kontrollon vete nese procedura e ka @KOLONAT, keshtu qe radha e perditesimit (SQL/aplikacion) s'ka rendesi.
-- Rikthimi: 05-rollback-eksport-magazina.sql

-- 27 - Konfigurimi i gridave, kontrolleve dhe te drejtave te raporteve (lexohen ne cdo hapje faqeje)
--
-- prc_T_GRIDATRUPI_* (kolonat e gridave), prc_T_KONTROLLE_* (kontrollet e formes) dhe prc_Moduli_RaportetSipasTeDrejtave
-- thirren disa here per cdo faqe. T_GRIDATRUPI, T_GRIDAKOKA dhe T_KONTROLLE kishin vetem celesin primar per keto kerkime,
-- keshtu qe cdo thirrje lexonte gjithe tabelen (T_GRIDATRUPI: 54 mije rreshta ne DRAFT, me shume te klientet).
-- Indekset jane te ngushta, vetem per lexim; nuk ndryshojne te dhena apo sjellje.
-- Rikthimi: 27-rollback-konfigurim-grida-indekse.sql
EXEC dbo.prc_OPTIMIZIM_Ruaj '27', N'dbo.T_GRIDATRUPI', N'IX_T_GRIDATRUPI_GRIDAKOKAID';
EXEC dbo.prc_OPTIMIZIM_Ruaj '27', N'dbo.T_GRIDAKOKA', N'IX_T_GRIDAKOKA_KOMP_KONFIG';
EXEC dbo.prc_OPTIMIZIM_Ruaj '27', N'dbo.T_GRIDAKOKA', N'IX_T_GRIDAKOKA_EMRI';
EXEC dbo.prc_OPTIMIZIM_Ruaj '27', N'dbo.T_LUPAMULTIPLE', N'IX_T_LUPAMULTIPLE_GRIDATRUPIID';
EXEC dbo.prc_OPTIMIZIM_Ruaj '27', N'dbo.T_KONTROLLE', N'IX_T_KONTROLLE_KOMPONENTE_KOD';
EXEC dbo.prc_OPTIMIZIM_Ruaj '27', N'dbo.T_ROLDREJTATRUPI', N'IX_T_ROLDREJTATRUPI_RAPORTI';
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID(N'dbo.T_GRIDATRUPI') AND name = N'IX_T_GRIDATRUPI_GRIDAKOKAID')
    CREATE NONCLUSTERED INDEX IX_T_GRIDATRUPI_GRIDAKOKAID ON dbo.T_GRIDATRUPI (GRIDAKOKAID, GRIDATRUPIINDEX);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID(N'dbo.T_GRIDAKOKA') AND name = N'IX_T_GRIDAKOKA_KOMP_KONFIG')
    CREATE NONCLUSTERED INDEX IX_T_GRIDAKOKA_KOMP_KONFIG ON dbo.T_GRIDAKOKA (GRIDKOMPID, IDKONFIGURIM) INCLUDE (GRIDKOKAEMRI);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID(N'dbo.T_GRIDAKOKA') AND name = N'IX_T_GRIDAKOKA_EMRI')
    CREATE NONCLUSTERED INDEX IX_T_GRIDAKOKA_EMRI ON dbo.T_GRIDAKOKA (GRIDKOKAEMRI, GRIDKOMPID) INCLUDE (IDKONFIGURIM);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID(N'dbo.T_LUPAMULTIPLE') AND name = N'IX_T_LUPAMULTIPLE_GRIDATRUPIID')
    CREATE NONCLUSTERED INDEX IX_T_LUPAMULTIPLE_GRIDATRUPIID ON dbo.T_LUPAMULTIPLE (GRIDATRUPIID) INCLUDE (IDKONFIGAMBJENTELUPA);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID(N'dbo.T_KONTROLLE') AND name = N'IX_T_KONTROLLE_KOMPONENTE_KOD')
    CREATE NONCLUSTERED INDEX IX_T_KONTROLLE_KOMPONENTE_KOD ON dbo.T_KONTROLLE (IDKOMPONENTE, KODKONTROLL);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID(N'dbo.T_ROLDREJTATRUPI') AND name = N'IX_T_ROLDREJTATRUPI_RAPORTI')
    CREATE NONCLUSTERED INDEX IX_T_ROLDREJTATRUPI_RAPORTI ON dbo.T_ROLDREJTATRUPI (IDRAPORTI, IDDREJTAKOKA) INCLUDE (D_AMB)
        WHERE IDRAPORTI IS NOT NULL;
GO

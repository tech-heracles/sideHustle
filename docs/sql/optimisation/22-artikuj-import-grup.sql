-- 22 - Ruajtja e artikujve te importit ne grupe (prc_T_ARTIKULLI_ruajImport)
--
-- Importi i artikujve ruante cdo artikull me 5-6 vajtje-ardhje ne databaze (fillim transaksioni, kontrolli i kodit,
-- prc_T_ARTIKULLI_ins, kontrolli i kodbarit, prc_T_KODBARI_ins, commit). Kjo procedure ben te njejtat hapa, ne te njejten
-- rradhe dhe me te njejtat kushte si clsArtikulli.ruaj -> ruajArtikull, per nje artikull (transaksioni i vet), keshtu
-- qe aplikacioni dergon disa artikuj ne nje komande. Kontrollet jane ato te prc_T_ARTIKULLI_ekzistonArtikull dhe
-- prc_T_KODBARI_ekzistonKodbar; parametrat jane ata te prc_T_ARTIKULLI_ins (te njejtat tipe) plus kodbari i vetem i artikullit
-- (@KAKODBAR = 1); artikujt me shume kodbare ruhen me rrugen e zakonshme. Kodbari jepet me parametra te thjeshte dhe jo me
-- tabele (table-valued parameter), sepse kjo e fundit kushton ~2.5 ms per thirrje, me shume se vete ruajtja.
-- @GABIMI: 0 u ruajt, 1 ekziston kodi, 2 ekziston kodbari, 3 gabim tjeter (@KODBARIGABIM = mesazhi;
-- aplikacioni e ruan ate artikull perseri me rrugen e zakonshme).
-- Rikthimi: 22-rollback-artikuj-import-grup.sql
SET ANSI_NULLS ON
GO
SET QUOTED_IDENTIFIER ON
GO
CREATE OR ALTER PROCEDURE dbo.prc_T_ARTIKULLI_ruajImport
(
    @IDARTIKULLI T_AUTO_NUM = null output,
    @KODARTIKULLI VARCHAR(50),
    @PERSHKRIMARTIKULLI varchar(1000),
    @PERSHKRIMIANGARTIKULLI varchar(1000),
    @KODIDOGANORARTIKULLI T_PERSHKRIM,
    @VENDODHJEARTIKULLI T_PERSHKRIM,
    @KODIFIKIMI1ARTIKULLI T_FOR_KEY,
    @KODIFIKIMI2ARTIKULLI T_FOR_KEY,
    @ORIGJINEARTIKULLI T_PERSHKRIM,
    @NJESI1ARTIKULLI T_FOR_KEY,
    @NJESI2ARTIKULLI T_FOR_KEY,
    @KOEFICENTARTIKULLI DECIMAL(18,10),
    @IDFURNITORIKRYESOR T_FOR_KEY,
    @PESHABRUTOARTIKULLI DECIMAL(18,2),
    @PESHANETOARTIKULLI DECIMAL(18,2),
    @DETAJIMARTIKULLI T_BOOLEAN,
    @KLASA INT,
    @IDSKEMAKONTABILITETIARTIKULLI T_FOR_KEY,
    @IDLLOGARIINVENTARI T_FOR_KEY,
    @IDLLOGARIBLERJE T_FOR_KEY,
    @IDLLOGARISHITJE T_FOR_KEY,
    @IDLLOGARITETRETE T_FOR_KEY,
    @IDLLOGARISHPENZIME T_FOR_KEY,
    @MINIMUMARTIKULLI DECIMAL(18,2),
    @MAXIMUMARTIKULLI DECIMAL(18,2),
    @METODEKOSTOJEARTIKULLI INT,
    @LLOGARITJAKMSHARTIKULLI INT,
    @ZEVENDESIMAUTOMATIKARTIKULLI INT,
    @IDPERDORUESI T_FOR_KEY,
    @IDNDERMARJE T_FOR_KEY,
    @KONTROLLGJENDJE T_BOOLEAN,
    @KONTROLLCMIMI T_BOOLEAN,
    @KONTROLLGJENDJEARTIKULLI T_BOOLEAN,
    @IDTVSH T_fOR_KEY,
    @IDKONFIG T_FOR_KEY,
    @AKTIV T_BOOLEAN,
    @IDSTATUSDOK T_FOR_KEY,
    @LLOJIART T_BOOLEAN,
    @IDLLOGARIAMORTIZIMI T_FOR_KEY,
    @SASINJESI DECIMAL(18,2),
    @SCRAP DECIMAL(18,2),
    @PRODHIMMEPOROSI T_BOOLEAN,
    @IDKATEGORIDETAJIMI T_FOR_KEY,
    @IDKATEGORIDETAJIMI2 T_FOR_KEY,
    @KONTROLLGJENDJEDETAJIM2 T_BOOLEAN,
    @IDOBJEKTIVAKOSTO T_FOR_KEY,
    @IDLLOJGARANCIA T_FOR_KEY,
    @GARANCIA DECIMAL(18,2),
    @IDMAGAZINA T_FOR_KEY,
    @IREZERVUESHEM t_boolean,
    @PERTRANSFERIM t_boolean,
    @LOAN T_bOOLEAN,
    @DHURATE T_BOOLEAN,
    @APLIKIMDHURATE T_KONST,
    @PIKE DECIMAL(18,2),
    @VLERE DECIMAL (18,2),
    @KODVFONE T_KOD_VAR,
    @MESERIAL T_BOOLEAN,
    @IDLLOGARIPAKESIM T_FOR_KEY,
    @ISHITSHEM BIT,
    @MBETJESHITJSHME t_boolean,
    @IDARTRAPORTUESI T_FOR_KEY,
    @PERPESHORE t_boolean,
    @PERSHKRIMTEFURNITORI T_PERSHKRIM,
    @SIPERFAQJAM2 varchar(500),
    @NRKONTRATE varchar(500),
    @SHASIA varchar(500),
    @NRPASURIE varchar(500),
    @ZONAKADASTRALE varchar(500),
    @MARKA varchar(500),
    @MODELI varchar(500),
    @VITPRODHIMI varchar(500),
    @TEDHENATEKNIKE varchar(500),
    @MEBARKODLOGJIK T_BOOLEAN,
    @SKEMABARKODIT T_PERSHKRIM,
    @KODIFIKIMI3ARTIKULLI t_for_key,
    @APARATBAZAAR bit,
    @KODOFERTE dbo.T_KOD_VAR,
    @ARTIKULLIVJETER bit,
    @IDKATEGORISERIALI dbo.T_FOR_KEY,
    @REZERVERIVLERESIMI BIT,
    @IDLLOGARIREZERVE T_FOR_KEY,
    @IDLLOGARIPAKESIMREZ T_FOR_KEY,
    @KARAKTERETAC int,
    @LLOGARITKOMISION BIT,
    @IDLLOGARIKOMISIONI int,
    @STOKUMAXVFONE INT,
    @KODIIBARIT VARCHAR(50),
    @IRIMBURSUESHEM BIT,
    @KAKODBAR BIT = 0,
    @KODBARI T_PERSHKRIM = NULL,
    @KODBARINJESIA INT = NULL,
    @KODBARIDETAJIM1 T_FOR_KEY = NULL,
    @KODBARIDETAJIM2 T_FOR_KEY = NULL,
    @GABIMI INT = 0 OUTPUT,
    @KODBARIGABIM NVARCHAR(4000) = NULL OUTPUT
)
AS
BEGIN
    SET NOCOUNT ON;
    SET @GABIMI = 0;
    SET @KODBARIGABIM = NULL;

    -- si prc_T_ARTIKULLI_ekzistonArtikull (kontrolloArtikull ne ruaj, para insert-it)
    IF EXISTS (SELECT 1 FROM T_ARTIKULLI WHERE KODARTIKULLI = @KODARTIKULLI AND IDNDERMARJE = @IDNDERMARJE AND idstatusdok <> 2)
    BEGIN
        SET @GABIMI = 1;
        SET @IDARTIKULLI = NULL;
        RETURN 0;
    END

    DECLARE @tc INT = @@TRANCOUNT;
    BEGIN TRY
        IF @tc = 0 BEGIN TRANSACTION; ELSE SAVE TRANSACTION ruajImport;

        EXEC prc_T_ARTIKULLI_ins
            @IDARTIKULLI = @IDARTIKULLI OUTPUT,
            @KODARTIKULLI = @KODARTIKULLI,
            @PERSHKRIMARTIKULLI = @PERSHKRIMARTIKULLI,
            @PERSHKRIMIANGARTIKULLI = @PERSHKRIMIANGARTIKULLI,
            @KODIDOGANORARTIKULLI = @KODIDOGANORARTIKULLI,
            @VENDODHJEARTIKULLI = @VENDODHJEARTIKULLI,
            @KODIFIKIMI1ARTIKULLI = @KODIFIKIMI1ARTIKULLI,
            @KODIFIKIMI2ARTIKULLI = @KODIFIKIMI2ARTIKULLI,
            @ORIGJINEARTIKULLI = @ORIGJINEARTIKULLI,
            @NJESI1ARTIKULLI = @NJESI1ARTIKULLI,
            @NJESI2ARTIKULLI = @NJESI2ARTIKULLI,
            @KOEFICENTARTIKULLI = @KOEFICENTARTIKULLI,
            @IDFURNITORIKRYESOR = @IDFURNITORIKRYESOR,
            @PESHABRUTOARTIKULLI = @PESHABRUTOARTIKULLI,
            @PESHANETOARTIKULLI = @PESHANETOARTIKULLI,
            @DETAJIMARTIKULLI = @DETAJIMARTIKULLI,
            @KLASA = @KLASA,
            @IDSKEMAKONTABILITETIARTIKULLI = @IDSKEMAKONTABILITETIARTIKULLI,
            @IDLLOGARIINVENTARI = @IDLLOGARIINVENTARI,
            @IDLLOGARIBLERJE = @IDLLOGARIBLERJE,
            @IDLLOGARISHITJE = @IDLLOGARISHITJE,
            @IDLLOGARITETRETE = @IDLLOGARITETRETE,
            @IDLLOGARISHPENZIME = @IDLLOGARISHPENZIME,
            @MINIMUMARTIKULLI = @MINIMUMARTIKULLI,
            @MAXIMUMARTIKULLI = @MAXIMUMARTIKULLI,
            @METODEKOSTOJEARTIKULLI = @METODEKOSTOJEARTIKULLI,
            @LLOGARITJAKMSHARTIKULLI = @LLOGARITJAKMSHARTIKULLI,
            @ZEVENDESIMAUTOMATIKARTIKULLI = @ZEVENDESIMAUTOMATIKARTIKULLI,
            @IDPERDORUESI = @IDPERDORUESI,
            @IDNDERMARJE = @IDNDERMARJE,
            @KONTROLLGJENDJE = @KONTROLLGJENDJE,
            @KONTROLLCMIMI = @KONTROLLCMIMI,
            @KONTROLLGJENDJEARTIKULLI = @KONTROLLGJENDJEARTIKULLI,
            @IDTVSH = @IDTVSH,
            @IDKONFIG = @IDKONFIG,
            @AKTIV = @AKTIV,
            @IDSTATUSDOK = @IDSTATUSDOK,
            @LLOJIART = @LLOJIART,
            @IDLLOGARIAMORTIZIMI = @IDLLOGARIAMORTIZIMI,
            @SASINJESI = @SASINJESI,
            @SCRAP = @SCRAP,
            @PRODHIMMEPOROSI = @PRODHIMMEPOROSI,
            @IDKATEGORIDETAJIMI = @IDKATEGORIDETAJIMI,
            @IDKATEGORIDETAJIMI2 = @IDKATEGORIDETAJIMI2,
            @KONTROLLGJENDJEDETAJIM2 = @KONTROLLGJENDJEDETAJIM2,
            @IDOBJEKTIVAKOSTO = @IDOBJEKTIVAKOSTO,
            @IDLLOJGARANCIA = @IDLLOJGARANCIA,
            @GARANCIA = @GARANCIA,
            @IDMAGAZINA = @IDMAGAZINA,
            @IREZERVUESHEM = @IREZERVUESHEM,
            @PERTRANSFERIM = @PERTRANSFERIM,
            @LOAN = @LOAN,
            @DHURATE = @DHURATE,
            @APLIKIMDHURATE = @APLIKIMDHURATE,
            @PIKE = @PIKE,
            @VLERE = @VLERE,
            @KODVFONE = @KODVFONE,
            @MESERIAL = @MESERIAL,
            @IDLLOGARIPAKESIM = @IDLLOGARIPAKESIM,
            @ISHITSHEM = @ISHITSHEM,
            @MBETJESHITJSHME = @MBETJESHITJSHME,
            @IDARTRAPORTUESI = @IDARTRAPORTUESI,
            @PERPESHORE = @PERPESHORE,
            @PERSHKRIMTEFURNITORI = @PERSHKRIMTEFURNITORI,
            @SIPERFAQJAM2 = @SIPERFAQJAM2,
            @NRKONTRATE = @NRKONTRATE,
            @SHASIA = @SHASIA,
            @NRPASURIE = @NRPASURIE,
            @ZONAKADASTRALE = @ZONAKADASTRALE,
            @MARKA = @MARKA,
            @MODELI = @MODELI,
            @VITPRODHIMI = @VITPRODHIMI,
            @TEDHENATEKNIKE = @TEDHENATEKNIKE,
            @MEBARKODLOGJIK = @MEBARKODLOGJIK,
            @SKEMABARKODIT = @SKEMABARKODIT,
            @KODIFIKIMI3ARTIKULLI = @KODIFIKIMI3ARTIKULLI,
            @APARATBAZAAR = @APARATBAZAAR,
            @KODOFERTE = @KODOFERTE,
            @ARTIKULLIVJETER = @ARTIKULLIVJETER,
            @IDKATEGORISERIALI = @IDKATEGORISERIALI,
            @REZERVERIVLERESIMI = @REZERVERIVLERESIMI,
            @IDLLOGARIREZERVE = @IDLLOGARIREZERVE,
            @IDLLOGARIPAKESIMREZ = @IDLLOGARIPAKESIMREZ,
            @KARAKTERETAC = @KARAKTERETAC,
            @LLOGARITKOMISION = @LLOGARITKOMISION,
            @IDLLOGARIKOMISIONI = @IDLLOGARIKOMISIONI,
            @STOKUMAXVFONE = @STOKUMAXVFONE,
            @KODIIBARIT = @KODIIBARIT,
            @IRIMBURSUESHEM = @IRIMBURSUESHEM;

        IF @KAKODBAR = 1
        BEGIN
            -- si prc_T_KODBARI_ekzistonKodbar (ruajArtikull, pas insert-it te artikullit, para kodbarit)
            IF EXISTS (SELECT 1 FROM T_KODBARI WHERE PERSHKRIMI = @KODBARI
                       AND IDARTIKULLI IN (SELECT IDARTIKULLI FROM T_ARTIKULLI WHERE IDNDERMARJE = @IDNDERMARJE AND IDSTATUSDOK <> 2))
            BEGIN
                IF @tc = 0 ROLLBACK TRANSACTION; ELSE ROLLBACK TRANSACTION ruajImport;
                SET @GABIMI = 2;
                SET @IDARTIKULLI = NULL;
                RETURN 0;
            END

            EXEC prc_T_KODBARI_ins @IDARTIKULLI, @KODBARI, @KODBARINJESIA, @KODBARIDETAJIM1, @KODBARIDETAJIM2;
        END

        IF @tc = 0 COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF @tc = 0 AND @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
        ELSE IF @tc > 0 AND XACT_STATE() = 1 ROLLBACK TRANSACTION ruajImport;
        SET @GABIMI = 3;
        SET @KODBARIGABIM = ERROR_MESSAGE();
        SET @IDARTIKULLI = NULL;
    END CATCH
    RETURN 0;
END
GO

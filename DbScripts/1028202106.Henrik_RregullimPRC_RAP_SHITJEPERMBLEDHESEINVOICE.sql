DECLARE @IDPARAMETRIDTDOK T_FOR_KEY = (SELECT IDPARAMETRI FROM T_PARAM WHERE SPPARAMETEREMRI = 'filterDtDok' AND SPCOLDBEMERLOGJIK = 'T_FATURAEINVOICE.DueDateTime')
DECLARE @IDPARAMETRIEIC T_FOR_KEY = (SELECT IDPARAMETRI FROM T_PARAM WHERE SPPARAMETEREMRI = 'filterEIC' AND SPCOLDBEMERLOGJIK = 'T_FATURAEINVOICE.EIC')
DECLARE @IDPARAMETRISTATUSEINVOICE T_FOR_KEY = (SELECT IDPARAMETRI FROM T_PARAM WHERE SPPARAMETEREMRI = 'filterStatusEinvoice' AND SPCOLDBEMERLOGJIK = 'T_FATURAEINVOICE.Status')
DECLARE @IDSP T_FOR_KEY = (SELECT IDSP FROM T_SP WHERE SPEMRI = 'PRC_RAP_SHITJEPERMBLEDHESEINVOICE')

if NOT EXISTS(SELECT * FROM T_PARAMXSP where IDPARAMETRI = @IDPARAMETRIDTDOK AND IDSP = @IDSP)

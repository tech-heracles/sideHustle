if NOT EXISTS(SELECT * FROM T_PARAMXSP where IDPARAMETRI = @IDPARAMETRISTATUSEINVOICE AND IDSP = @IDSP)
BEGIN
	INSERT INTO T_PARAMXSP(IDSP,IDPARAMETRI)
	VALUES (@IDSP,@IDPARAMETRISTATUSEINVOICE)
END